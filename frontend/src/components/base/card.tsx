import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * shadcn Card 基础件(21st.dev 同源)
 * 雪球风: 极轻边框 + 极轻阴影 + 12px 圆角
 */
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-card border border-border bg-bg-card text-text-primary shadow-card",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

